const path = require('node:path');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const out = path.join(root, '.scratch/focus-shift-built');
execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', 'src/island/fsm.ts', '--outDir', out, '--module', 'commonjs', '--target', 'es2020', '--lib', 'es2020,dom', '--skipLibCheck'], { cwd: path.join(root, 'windows'), stdio: 'inherit' });
const timers = new Map();
let id = 0;
global.window = { setTimeout: fn => { timers.set(++id, fn); return id; }, clearTimeout: key => timers.delete(key) };
const { IslandStateMachine } = require(path.join(out, 'fsm.js'));
const fsm = new IslandStateMachine();
fsm.forceHome();
fsm.mouseLeft();
assert.equal(timers.size, 1);
fsm.focusShift();
assert.equal(fsm.state, 'hidden');
assert.equal(timers.size, 0, 'app switch cancels the old close timer');
fsm.reveal();
fsm.focusShift();
assert.equal(fsm.state, 'hidden', 'compact card also closes on an app switch');
fsm.forceHome();
fsm.pinned = true;
fsm.focusShift();
assert.equal(fsm.state, 'home', 'pinned permission remains open');
fsm.pinned = false;
fsm.focusShift();
fsm.mouseEntered();
assert.equal(fsm.state, 'petit', 'hover can wake after focus dismissal');
console.log('PASS: focus shift closes promptly, clears timers, preserves pins and permits waking');
